# GPUCompiler's NVVM back-end requires libNVVM from CUDA 13.5 (earlier versions miscompile
# atomics)
nvvm_supported = CUDACore.compiler_version() >= v"13.5"

if nvvm_supported

@testset "execution" begin
    function kernel(a, b)
        i = threadIdx().x
        @inbounds b[i] = sin(a[i]) + 1f0
        return
    end
    a = CUDA.rand(Float32, 32)
    b = similar(a)
    @cuda threads=32 codegen=:nvvm kernel(a, b)
    @test Array(b) ≈ sin.(Array(a)) .+ 1f0
end

@testset "reflection" begin
    @test @filecheck CUDA.code_ptx(Tuple{Ptr{Float32}}; codegen=:nvvm) do ptr
        @check "Generated by NVIDIA NVVM Compiler"
        unsafe_store!(ptr, 1f0)
        return
    end
end

@testset "exceptions" begin
    # the thread has to exit after reporting the exception, keeping the context usable
    function kernel(a, i)
        a[i] = 1f0
        return
    end
    a = CUDA.zeros(Float32, 1)
    @test_throws CUDACore.KernelException begin
        @cuda codegen=:nvvm kernel(a, 2)
        synchronize()
    end
    @cuda codegen=:nvvm kernel(a, 1)
    @test Array(a) == [1f0]
end

end

@testset "NVPTX back-end" begin
    # regardless of the default
    @test @filecheck CUDA.code_ptx(Tuple{Ptr{Float32}}; codegen=:nvptx) do ptr
        @check "Generated by LLVM NVPTX Back-End"
        unsafe_store!(ptr, 1f0)
        return
    end
    kernel() = return
    @cuda codegen=:nvptx kernel()
    synchronize()
end

@testset "invalid options" begin
    kernel() = return
    @test_throws "cannot be combined with `codegen=:nvvm`" @cuda launch=false codegen=:nvvm ptx=v"8.0" kernel()
    @test_throws "`codegen` must be one of" @cuda launch=false codegen=:foo kernel()
end
