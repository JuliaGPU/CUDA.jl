# libNVVM's reader for the LLVM IR Julia generates needs CUDA 13.5, or 13.2 on Blackwell
nvvm_supported = CUDACore.compiler_version() >= v"13.5" ||
                 (CUDACore.compiler_version() >= v"13.2" && capability(device()) >= v"10.0")

struct CountedArgument{T}
    value::T
    counter::Base.RefValue{Int}
end
struct ConvertedArgument{T}
    value::T
end
function Adapt.adapt_structure(to::CUDA.KernelAdaptor, arg::CountedArgument)
    arg.counter[] += 1
    ConvertedArgument(Adapt.adapt(to, arg.value))
end
Adapt.adapt_structure(to::CUDA.KernelAdaptor, arg::ConvertedArgument) =
    error("argument converted twice")
function copy_counted(arg, output)
    output[1] = arg.value[1]
    return
end

if nvvm_supported

@testset "execution" begin
    function kernel(a, b)
        i = threadIdx().x
        @inbounds b[i] = sin(a[i]) + 1f0
        return
    end
    a = CUDA.rand(Float32, 32)
    b = similar(a)
    @cuda threads=32 codegen=:nvvm kernel(a, b)
    @test Array(b) ≈ sin.(Array(a)) .+ 1f0

    b .= 0
    @cuda threads=32 backend=CUDA.NVVMBackend() kernel(a, b)
    @test Array(b) ≈ sin.(Array(a)) .+ 1f0
end

@testset "argument conversion" begin
    # the backend shares `LLVMBackend`'s launch path, which converts arguments once
    counter = Ref(0)
    arg = CountedArgument(CuArray([42f0]), counter)
    output = CuArray([0f0])
    @cuda backend=CUDA.NVVMBackend() copy_counted(arg, output)
    @test counter[] == 1
    @test Array(output) == [42f0]
end

@testset "reflection" begin
    @test @filecheck CUDA.code_ptx(Tuple{Ptr{Float32}}; codegen=:nvvm) do ptr
        @check "Generated by NVIDIA NVVM Compiler"
        unsafe_store!(ptr, 1f0)
        return
    end
end

@testset "exceptions" begin
    # the thread has to exit after reporting the exception, keeping the context usable
    function kernel(a, i)
        a[i] = 1f0
        return
    end
    a = CUDA.zeros(Float32, 1)
    @test_throws CUDACore.KernelException begin
        @cuda codegen=:nvvm kernel(a, 2)
        synchronize()
    end
    @cuda codegen=:nvvm kernel(a, 1)
    @test Array(a) == [1f0]
end

end

@testset "NVPTX back-end" begin
    # regardless of the default
    @test @filecheck CUDA.code_ptx(Tuple{Ptr{Float32}}; codegen=:nvptx) do ptr
        @check "Generated by LLVM NVPTX Back-End"
        unsafe_store!(ptr, 1f0)
        return
    end
    kernel() = return
    @cuda backend=CUDA.NVPTXBackend() kernel()
    synchronize()
end

@testset "invalid options" begin
    kernel() = return
    @test_throws "cannot be combined with `codegen=:nvvm`" @cuda launch=false codegen=:nvvm ptx=v"8.0" kernel()
    @test_throws "`codegen` must be one of" @cuda launch=false codegen=:foo kernel()
end
